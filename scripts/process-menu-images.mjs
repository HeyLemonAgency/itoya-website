// Turns the official menu photos (one per dish, transparent cut-outs) into
// WebP files in public/images/menu/<dish-id>.webp (≤ 640 px, served through
// next/image), 128 px thumbnails in public/images/menu/thumbs/ (served as is
// in the menu rows on phones) and writes src/content/menu-images.ts.
//
//   python3 scripts/build-menu.py docs/sources/official-menu-snapshot-….json
//   node scripts/process-menu-images.mjs [--force]
//
// Originals are read from ./media-src (see scripts/fetch-originals.mjs).
// Existing 640 px files are reused unless --force is given.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sources = JSON.parse(readFileSync(join(root, "scripts/menu-image-sources.json"), "utf8"));
const outDir = join(root, "public/images/menu");
const thumbDir = join(outDir, "thumbs");
mkdirSync(thumbDir, { recursive: true });
const force = process.argv.includes("--force");

/**
 * Photos that look like supplier / stock imagery rather than Itoya's own
 * dishes are left out (see docs/ASSET_MANIFEST.md).
 */
const exclude = new Set([
  "banana-split",
  "coupe-danemark",
  "glace-citron",
  "glace-fraise",
  "glace-de-noix-de-coco",
  "mochi-mangue",
  "mochi-pistache",
  "mochi-vanille",
  "mochi-citron",
]);

const entries = {};
for (const [id, media] of Object.entries(sources).sort()) {
  if (exclude.has(id)) continue;
  const out = join(outDir, `${id}.webp`);
  let buf;
  if (existsSync(out) && !force) {
    buf = readFileSync(out);
  } else {
    const file = join(root, "media-src", media.replace(/~/g, "_"));
    if (!existsSync(file)) {
      console.warn(`missing original for ${id}`);
      continue;
    }
    buf = await sharp(file)
      .rotate()
      .ensureAlpha()
      .trim({ threshold: 1 })
      .resize({ width: 640, height: 640, fit: "inside", withoutEnlargement: true })
      .webp({ quality: 84, alphaQuality: 100, effort: 6 })
      .toBuffer();
    writeFileSync(out, buf);
  }
  const { width, height } = await sharp(buf).metadata();
  // 64 px rows at 2× density.
  await sharp(buf)
    .resize({ width: 128, height: 128, fit: "inside" })
    .webp({ quality: 80, alphaQuality: 90, effort: 6 })
    .toFile(join(thumbDir, `${id}.webp`));
  entries[id] = {
    src: `/images/menu/${id}.webp`,
    width,
    height,
    thumb: `/images/menu/thumbs/${id}.webp`,
  };
}

const ts = `// Generated by scripts/process-menu-images.mjs — do not edit by hand.
// Dish photos from the official itoya.ch menu (transparent cut-outs).

export type DishImage = {
  src: string;
  width: number;
  height: number;
  /** 128 px version for the 64 px menu rows (served as is). */
  thumb: string;
};

export const menuImages: Record<string, DishImage> = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(root, "src/content/menu-images.ts"), ts);
console.log(`menu images: ${Object.keys(entries).length} written, ${exclude.size} excluded`);
